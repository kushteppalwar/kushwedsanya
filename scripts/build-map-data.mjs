// One-off generator: turns world-atlas topojson into the plain lon/lat ring
// arrays the 3D scene (components/v4-1/mapScene.tsx) draws on the ground.
// Run with `node scripts/build-map-data.mjs` whenever the source data changes;
// the output is committed under lib/mapData/ so the app never depends on
// world-atlas/topojson-client at runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { feature } from "topojson-client";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const atlas = (name) => JSON.parse(readFileSync(path.join(root, "node_modules/world-atlas", name), "utf8"));

/** Rounds to keep the file small; ~1.1km at the equator, plenty for a low-poly globe. */
const round = (n) => Math.round(n * 100) / 100;

/**
 * A handful of coastlines (Chukotka, Fiji…) genuinely straddle ±180°. Traced as a
 * single ring that reads as a ~360° jump in raw longitude — which, left alone, turns
 * into a giant stretched sliver once projected. Unwrap by letting longitude run past
 * ±180 instead of snapping back, so the ring stays a sane, continuous shape.
 *
 * Sequential unwrapping alone isn't enough: a ring can start its point list right in
 * the sliver that needs shifting, in which case a plain running offset shifts the
 * *majority* of the ring (all of Eurasia, say) instead of the small part that
 * actually needs it. So re-base afterwards on whichever offset most of the ring
 * landed on — that's the "normal" reference frame, and the sliver moves to meet it.
 */
function unwrap(ring) {
  let offset = 0;
  const offsets = [0];
  for (let i = 1; i < ring.length; i += 1) {
    const prev = ring[i - 1][0];
    const lon = ring[i][0];
    if (lon - prev > 180) offset -= 360;
    else if (lon - prev < -180) offset += 360;
    offsets.push(offset);
  }
  const counts = new Map();
  offsets.forEach((o) => counts.set(o, (counts.get(o) ?? 0) + 1));
  let modeOffset = 0, modeCount = -1;
  counts.forEach((count, o) => {
    if (count > modeCount) {
      modeCount = count;
      modeOffset = o;
    }
  });
  return ring.map(([lon, lat], i) => [lon + offsets[i] - modeOffset, lat]);
}

/** GeoJSON polygon → [exterior, ...holes], each ring a closed [lon, lat] loop. */
function polygonsOf(geometry) {
  const polygons = geometry.type === "MultiPolygon" ? geometry.coordinates : [geometry.coordinates];
  return polygons.map((polygon) =>
    polygon.map((ring) => unwrap(ring).map(([lon, lat]) => [round(lon), round(lat)])),
  );
}

function bbox(ring) {
  let minLon = Infinity, maxLon = -Infinity, minLat = Infinity, maxLat = -Infinity;
  for (const [lon, lat] of ring) {
    minLon = Math.min(minLon, lon);
    maxLon = Math.max(maxLon, lon);
    minLat = Math.min(minLat, lat);
    maxLat = Math.max(maxLat, lat);
  }
  return { minLon, maxLon, minLat, maxLat };
}

function bboxDiagonal(ring) {
  const { minLon, maxLon, minLat, maxLat } = bbox(ring);
  return Math.hypot(maxLon - minLon, maxLat - minLat);
}

function writePolygons(relPath, exportName, description, polygons) {
  const body = polygons.map((polygon) => JSON.stringify(polygon)).join(",\n  ");
  const rings = polygons.reduce((n, p) => n + p.length, 0);
  const points = polygons.reduce((n, p) => n + p.reduce((m, r) => m + r.length, 0), 0);
  const source = `// Generated by scripts/build-map-data.mjs from world-atlas — do not hand-edit.
// ${description}
/** Each polygon is [exterior, ...holes]; each ring a closed [lon, lat] loop, degrees. */
export const ${exportName}: [number, number][][][] = [
  ${body}
];
`;
  writeFileSync(path.join(root, relPath), source);
  console.log(`wrote ${relPath}: ${polygons.length} polygons, ${rings} rings, ${points} points`);
}

// ─── World: merged landmass, tiny islands dropped so the globe reads as continents ───
// Antarctica dropped too: no guest is coming from there, and it's a circumpolar ring
// that distorts badly (and stretches the whole scene) in this flat lon/lat projection.
const land = atlas("land-110m.json");
const landFeature = feature(land, land.objects.land).features[0];
const worldPolygons = polygonsOf(landFeature.geometry).filter((polygon) => {
  const { maxLat } = bbox(polygon[0]);
  return bboxDiagonal(polygon[0]) >= 3 && maxLat > -60;
});
writePolygons(
  "lib/mapData/world.ts",
  "WORLD_LAND",
  "Rough continent outlines (world-atlas land-110m, islands under ~3° dropped).",
  worldPolygons,
);

// ─── India: the actual country outline (mainland + the larger island groups) ───
const countries = atlas("countries-50m.json");
const india = feature(countries, countries.objects.countries).features.find((f) => f.properties?.name === "India");
if (!india) throw new Error("India not found in countries-50m.json");
const indiaPolygons = polygonsOf(india.geometry);
writePolygons(
  "lib/mapData/india.ts",
  "INDIA_OUTLINE",
  "India's outline, mainland + islands (world-atlas countries-50m).",
  indiaPolygons,
);
